async function main() {
  const familyId = process.argv[2];

  if (!familyId) {
    console.log("Användning: node supabase/seed-missing.mjs <family_id>\n");
    const families = await listFamilies();
    if (families.length === 0) {
      console.log("  (inga familjer)");
    } else {
      for (const f of families) console.log(`  ${f.id}  ${f.name}`);
    }
    process.exit(0);
  }

  const existing = await getExistingTitles(familyId);
  const toInsert = recipes.filter((r) => !existing.has(r.title.toLowerCase().trim()));

  console.log(`Totalt ${recipes.length} recept i skriptet.`);
  console.log(`${existing.size} recept finns redan i databasen.`);
  console.log(`${toInsert.length} nya recept att lägga in.\n`);

  let ok = 0;
  let fail = 0;

  for (const r of toInsert) {
    try {
      const [inserted] = await api("recipes", {
        family_id: familyId,
        title: r.title,
        description: r.description,
        instructions: r.instructions,
        category: r.category,
        source: "Familjen Frosts Kokbok",
        servings: r.servings,
        is_active: true,
      });

      if (r.ingredients.length > 0) {
        await api(
          "recipe_ingredients",
          r.ingredients.map((ing, i) => ({
            recipe_id: inserted.id,
            ingredient: ing.ingredient,
            amount: ing.amount,
            unit: ing.unit,
            sort_order: i,
          })),
        );
      }

      console.log(`  ✓ ${r.title}`);
      ok++;
    } catch (e) {
      console.error(`  ✗ ${r.title}: ${e.message}`);
      fail++;
    }
  }

  console.log(`\nKlart! ${ok} lyckades, ${fail} misslyckades.`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
