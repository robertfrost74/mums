async function api(path, body) {
  const res = await fetch(`${SUPABASE_URL}/rest/v1/${path}`, {
    method: "POST",
    headers,
    body: JSON.stringify(body),
  });
  if (!res.ok) {
    const text = await res.text();
    throw new Error(`${res.status} ${path}: ${text}`);
  }
  return res.json();
}

async function listFamilies() {
  const res = await fetch(`${SUPABASE_URL}/rest/v1/families?select=id,name`, { headers });
  return res.json();
}

async function getExistingTitles(familyId) {
  const res = await fetch(
    `${SUPABASE_URL}/rest/v1/recipes?select=title&family_id=eq.${familyId}`,
    { headers },
  );
  const data = await res.json();
  return new Set(data.map((r) => r.title.toLowerCase().trim()));
}

