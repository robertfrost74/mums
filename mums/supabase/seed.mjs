// ── Main ─────────────────────────────────────────────────────
async function main() {
  const familyId = process.argv[2];

  if (!familyId) {
    console.log("Användning: node supabase/seed.mjs <family_id>\n");
    console.log("Tillgängliga familjer:");
    const families = await listFamilies();
    if (families.length === 0) {
      console.log("  (inga familjer – registrera dig först i appen)");
    } else {
      for (const f of families) {
        console.log(`  ${f.id}  ${f.name}`);
      }
    }
    process.exit(0);
  }

  console.log(`Seedar ${recipes.length} recept till familj ${familyId}…\n`);

  let ok = 0;
  let fail = 0;

  for (const r of recipes) {
    try {
      const [inserted] = await api("recipes", {
        family_id: familyId,
        title: r.title,
        description: r.description,
        instructions: r.instructions,
        category: r.category,
        source: "Familjen Frosts Kokbok",
        servings: r.servings,
        is_active: true,
      });

      if (r.ingredients.length > 0) {
        await api(
          "recipe_ingredients",
          r.ingredients.map((ing, i) => ({
            recipe_id: inserted.id,
            ingredient: ing.ingredient,
            amount: ing.amount,
            unit: ing.unit,
            sort_order: i,
          })),
        );
      }

      console.log(`  ✓ ${r.title}`);
      ok++;
    } catch (e) {
      console.error(`  ✗ ${r.title}: ${e.message}`);
      fail++;
    }
  }

  console.log(`\nKlart! ${ok} lyckades, ${fail} misslyckades.`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
